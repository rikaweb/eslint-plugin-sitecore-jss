#!/usr/bin/env node
// Builds docs/AGENTS.sitecore-fields.md from the Claude Code skill, for coding agents that read an
// AGENTS.md (Cursor, GitHub Copilot, Codex, ...). The skill stays the single source: this file is
// generated, and `--check` (run by tests/agents-md.test.ts) fails when it is out of date.
//
//   node scripts/build-agents-md.mjs           write the file
//   node scripts/build-agents-md.mjs --check   exit 1 if the file on disk differs
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import process from "node:process";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const SKILL_DIR = "claude-plugin/skills/sitecore-fields";
const OUTPUT = "docs/AGENTS.sitecore-fields.md";
const REPO_URL = "https://github.com/rikaweb/eslint-plugin-sitecore-jss";
const BLOB_URL = `${REPO_URL}/blob/main/${SKILL_DIR}`;

const read = (path) => readFileSync(join(root, path), "utf8").replace(/\r\n/g, "\n");

/** Markdown blocks (separated by blank lines), keeping fenced code blocks in one piece. */
function blocks(markdown) {
  const result = [];
  let current = [];
  let fenced = false;
  for (const line of markdown.split("\n")) {
    if (/^\s*```/.test(line)) fenced = !fenced;
    if (line.trim() === "" && !fenced) {
      if (current.length) result.push(current.join("\n"));
      current = [];
    } else {
      current.push(line);
    }
  }
  if (current.length) result.push(current.join("\n"));
  return result;
}

/** Drops what only works inside Claude Code and points relative links at GitHub. */
function portable(markdown) {
  return blocks(markdown)
    .filter((block) => !/CLAUDE_PLUGIN_ROOT|\/jss:/.test(block))
    .join("\n\n")
    .replace(/\]\((references\/[\w-]+\.md)\)/g, `](${BLOB_URL}/$1)`)
    .replace(/\]\(([\w-]+\.md)\)/g, `](${BLOB_URL}/references/$1)`)
    .replace(/\b([Tt])his skill\b/g, "$1his guide");
}

/** The text of one `## ` section, heading included. */
function section(markdown, heading) {
  const start = markdown.indexOf(`## ${heading}\n`);
  if (start < 0) throw new Error(`Section "${heading}" not found; update scripts/build-agents-md.mjs`);
  const next = markdown.indexOf("\n## ", start + 1);
  return markdown.slice(start, next < 0 ? undefined : next).trimEnd();
}

function build() {
  const skill = read(`${SKILL_DIR}/SKILL.md`);
  const body = skill.replace(/^---\n[\s\S]*?\n---\n/, "");
  if (body === skill) throw new Error("SKILL.md has no frontmatter; update scripts/build-agents-md.mjs");
  const linter = read(`${SKILL_DIR}/references/linter.md`);
  const version = JSON.parse(read("claude-plugin/.claude-plugin/plugin.json")).version;

  const parts = [
    `<!-- Generated by scripts/build-agents-md.mjs from ${SKILL_DIR} (plugin ${version}). Do not edit. -->`,
    portable(body).trim(),
    "# Working with eslint-plugin-sitecore-jss",
    `Setup, every rule and every message id: [README](${REPO_URL}#readme) and [linter.md](${BLOB_URL}/references/linter.md).`,
    ...["Findings without a fix, and what to do", "What it never reports", "Known limits"].map((heading) =>
      portable(section(linter, heading)),
    ),
  ];
  return `${parts.join("\n\n")}\n`;
}

const output = build();
if (process.argv.includes("--check")) {
  let current = "";
  try {
    current = read(OUTPUT);
  } catch {
    // missing file: reported below
  }
  if (current !== output) {
    process.stderr.write(`${OUTPUT} is out of date. Run: node scripts/build-agents-md.mjs\n`);
    process.exit(1);
  }
} else {
  writeFileSync(join(root, OUTPUT), output);
  process.stdout.write(`Wrote ${OUTPUT} (${output.split("\n").length - 1} lines)\n`);
}
